import gzip, shutil, os

data = b"Bu ma'lumotlarni siqish orqali saqlash usuli. " * 100

with open('data.txt', 'wb') as f:
    f.write(data)

with open('data.txt', 'rb') as f_in:
    with gzip.open('data.txt.gz', 'wb') as f_out:
        shutil.copyfileobj(f_in, f_out)

a = os.path.getsize('data.txt')
b = os.path.getsize('data.txt.gz')
print("Asl hajm:", a, "bayt")
print("Siqilgan hajm:", b, "bayt")
print("Siqish darajasi:", round(a / b, 1), "marta")

with gzip.open('data.txt.gz', 'rb') as f:
    file_content = f.read()

print("Ochilgan ma'lumot:", file_content[:100])
print("Asl bilan bir xilmi?", file_content == data)